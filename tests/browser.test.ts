function pdf(text:string):Buffer{
  const content=`BT /F1 12 Tf 72 720 Td (${text}) Tj ET`;
  const o=['<< /Type /Catalog /Pages 2 0 R >>','<< /Type /Pages /Kids [3 0 R] /Count 1 >>','<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>',`<< /Length ${content.length} >>\nstream\n${content}\nendstream`,'<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>'];
  let s='%PDF-1.4\n';const pos=[0];for(let i=0;i<o.length;i++){pos.push(Buffer.byteLength(s));s+=`${i+1} 0 obj\n${o[i]}\nendobj\n`;}const x=Buffer.byteLength(s);s+=`xref\n0 6\n0000000000 65535 f \n`;for(const p of pos.slice(1))s+=`${String(p).padStart(10,'0')} 00000 n \n`;s+=`trailer\n<< /Size 6 /Root 1 0 R >>\nstartxref\n${x}\n%%EOF`;return Buffer.from(s);
}

